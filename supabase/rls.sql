  for insert with check (
    auth.uid() = user_id and auth.uid() = created_by
    and public.is_household_member(household_id)
  );

drop policy if exists "Users can update their own transactions" on public.transactions;
drop policy if exists "Creators and household owners can update transactions" on public.transactions;
create policy "Creators and household owners can update transactions" on public.transactions
  for update using (
    auth.uid() = created_by
    or exists (
      select 1 from public.household_members
      where household_id = transactions.household_id
        and user_id = auth.uid()
        and role = 'owner'
    )
  )
  with check (public.is_household_member(household_id));

drop policy if exists "Users can delete their own transactions" on public.transactions;
drop policy if exists "Creators and household owners can delete transactions" on public.transactions;
create policy "Creators and household owners can delete transactions" on public.transactions
  for delete using (
    auth.uid() = created_by
    or exists (
      select 1 from public.household_members
      where household_id = transactions.household_id
        and user_id = auth.uid()
        and role = 'owner'
    )
  );

