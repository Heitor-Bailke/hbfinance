drop policy if exists "Users can view their own profile" on public.profiles;
drop policy if exists "Users can view household profiles" on public.profiles;
create policy "Users can view household profiles" on public.profiles
  for select using (
    id = auth.uid() or exists (
      select 1 from public.household_members own
      join public.household_members other on other.household_id = own.household_id
      where own.user_id = auth.uid() and other.user_id = profiles.id
    )
  );

