create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do update
    set full_name = excluded.full_name,
        updated_at = now();
  insert into public.households (created_by)
  values (new.id);
  insert into public.household_members (household_id, user_id, role)
  select id, new.id, 'owner'
  from public.households
  where created_by = new.id
  order by created_at desc
  limit 1
  on conflict do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

insert into public.profiles (id, full_name)
select id, raw_user_meta_data ->> 'full_name'
from auth.users
on conflict (id) do nothing;

insert into public.households (created_by)
select p.id
from public.profiles p
where not exists (select 1 from public.households h where h.created_by = p.id);

insert into public.household_members (household_id, user_id, role)
select h.id, h.created_by, 'owner'
from public.households h
on conflict do nothing;

update public.transactions t
set created_by = t.user_id
where t.created_by is null;

update public.transactions t
set household_id = hm.household_id
from public.household_members hm
where t.household_id is null
  and hm.user_id = t.user_id;

do $$
begin
