    alter table public.transactions add constraint transactions_household_id_fkey
      foreign key (household_id) references public.households(id) on delete cascade;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_created_by_fkey') then
    alter table public.transactions add constraint transactions_created_by_fkey
      foreign key (created_by) references auth.users(id) on delete cascade;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_created_by_profile_fkey') then
    alter table public.transactions add constraint transactions_created_by_profile_fkey
      foreign key (created_by) references public.profiles(id) on delete cascade;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'household_members_user_profile_fkey') then
    alter table public.household_members add constraint household_members_user_profile_fkey
      foreign key (user_id) references public.profiles(id) on delete cascade;
  end if;
end $$;

create or replace function public.is_household_member(target_household uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.household_members
    where household_id = target_household and user_id = auth.uid()
  );
$$;

create or replace function public.invite_household_member(member_email text)
returns void language plpgsql security definer set search_path = public, auth
as $$
declare
  target_user uuid;
  target_household uuid;
  target_old_household uuid;
begin
  select household_id into target_household
  from public.household_members
  where user_id = auth.uid() and role = 'owner'
  limit 1;
  if target_household is null then raise exception 'Apenas o dono da conta pode convidar integrantes.'; end if;
  select id into target_user from auth.users
  where lower(email) = lower(trim(member_email)) limit 1;
  if target_user is null then raise exception 'Usuário não encontrado. Ele precisa criar uma conta primeiro.'; end if;
  select household_id into target_old_household
  from public.household_members
  where user_id = target_user and household_id <> target_household
  limit 1;
  if target_old_household is not null and target_old_household <> target_household then
    if (select count(*) from public.household_members where household_id = target_old_household) > 1 then
      raise exception 'Este usuário já participa de outra conta conjunta.';
    end if;
    update public.transactions
    set household_id = target_household
    where household_id = target_old_household;
    delete from public.households where id = target_old_household;
  end if;
  insert into public.household_members (household_id, user_id, role)
  values (target_household, target_user, 'member')
  on conflict do nothing;
end;
$$;

create or replace function public.remove_household_member(target_user uuid)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  target_household uuid;
  personal_household uuid;
begin
  select household_id into target_household
  from public.household_members
  where user_id = auth.uid() and role = 'owner'
  limit 1;
  if target_household is null then
    raise exception 'Apenas o dono da conta pode remover integrantes.';
  end if;
  if target_user = auth.uid() then
    raise exception 'O dono da conta não pode remover a si mesmo.';
  end if;
  if not exists (
    select 1
    from public.household_members
    where household_id = target_household
      and user_id = target_user
      and role = 'member'
  ) then
    raise exception 'Integrante não encontrado nesta conta.';
  end if;
  delete from public.household_members
  where household_id = target_household and user_id = target_user;
  if not exists (select 1 from public.household_members where user_id = target_user) then
    insert into public.households (created_by)
    values (target_user)
    returning id into personal_household;
    insert into public.household_members (household_id, user_id, role)
    values (personal_household, target_user, 'owner');
  end if;
end;
$$;

grant execute on function public.invite_household_member(text) to authenticated;
grant execute on function public.remove_household_member(uuid) to authenticated;

create or replace function public.leave_household()
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  target_household uuid;
  personal_household uuid;
begin
  select household_id into target_household
  from public.household_members
  where user_id = auth.uid() and role = 'member'
  limit 1;
  if target_household is null then
    raise exception 'Apenas integrantes podem sair da conta conjunta.';
  end if;
  delete from public.household_members
  where household_id = target_household and user_id = auth.uid();
  if not exists (select 1 from public.household_members where user_id = auth.uid()) then
    insert into public.households (created_by)
    values (auth.uid())
    returning id into personal_household;
    insert into public.household_members (household_id, user_id, role)
    values (personal_household, auth.uid(), 'owner');
  end if;
end;
$$;

grant execute on function public.leave_household() to authenticated;

create or replace function public.reset_current_balance()
returns timestamptz
language plpgsql
security definer set search_path = public
as $$
declare
  target_household uuid;
  current_balance numeric(12, 2);
  current_reset timestamptz;
  previous_reset timestamptz;
begin
  select household_id into target_household
  from public.household_members
  where user_id = auth.uid() and role = 'owner'
  limit 1;
  if target_household is null then
    raise exception 'Apenas o dono da conta pode zerar o saldo.';
  end if;
  select max(reset_at) into previous_reset
  from public.balance_resets
  where household_id = target_household;
  select coalesce(sum(case when tipo = 'receita' then valor else -valor end), 0)
    into current_balance
  from public.transactions
  where household_id = target_household
    and (previous_reset is null or created_at >= previous_reset);
  insert into public.balance_resets (household_id, reset_by, balance_before)
  values (target_household, auth.uid(), current_balance)
  returning reset_at into current_reset;
  return current_reset;
end;
$$;

grant execute on function public.reset_current_balance() to authenticated;

do $$
declare
  account record;
  personal_household uuid;
begin
  for account in
    select id
    from auth.users
    where not exists (
      select 1
      from public.household_members
      where user_id = auth.users.id
    )
  loop
    insert into public.households (created_by)
    values (account.id)
    returning id into personal_household;
    insert into public.household_members (household_id, user_id, role)
    values (personal_household, account.id, 'owner');
  end loop;
end $$;

create or replace function public.create_transaction_notifications()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.household_id is null then
    return new;
  end if;
  insert into public.notifications (user_id, household_id, transaction_id, title, body)
  select
    member.user_id,
    new.household_id,
    new.id::text,
    'Novo lançamento',
    coalesce(profile.full_name, 'Um integrante')
      || ' registrou '
      || case when new.tipo = 'receita' then 'uma receita' else 'uma despesa' end
      || ': '
      || new.descricao
  from public.household_members member
  left join public.profiles profile on profile.id = new.created_by
  where member.household_id = new.household_id
    and member.user_id <> new.created_by;
  return new;
end;
$$;

drop trigger if exists on_transaction_created on public.transactions;
create trigger on_transaction_created
  after insert on public.transactions
  for each row execute procedure public.create_transaction_notifications();

do $$
declare
  vinculo record;
begin
  for vinculo in
    select invited.household_id as target_household, old.household_id as old_household
    from public.household_members invited
    join public.household_members old
      on old.user_id = invited.user_id
     and old.household_id <> invited.household_id
     and old.role = 'owner'
    where invited.role = 'member'
      and (
        select count(*)
        from public.household_members members
        where members.household_id = old.household_id
      ) = 1
  loop
    update public.transactions
    set household_id = vinculo.target_household
    where household_id = vinculo.old_household;

    delete from public.households
    where id = vinculo.old_household;
  end loop;
end $$;

